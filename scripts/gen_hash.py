"""scripts/gen_hash.py — 生成产物哈希记录与校验。

gen 后把所有生成产物的 sha256 写入 packages/schema/.gen-hash.json；
check-gen 用它检出「生成产物被手改」的情况（配合 gen_ts.mjs --check 与
gen_python_models.py --check 检出「schema 改了但没重新生成」）。

用法：python scripts/gen_hash.py [--check]
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
HASH_FILE = REPO / "packages" / "schema" / ".gen-hash.json"

GENERATED_FILES = [
    "packages/schema/generated/ts/trace-event.d.ts",
    "packages/schema/generated/ts/metric-set.d.ts",
    "packages/schema/generated/ts/taskset.d.ts",
    "packages/schema/generated/ts/capability.d.ts",
    "engine/hs_core/models.py",
]


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generator_versions() -> dict[str, str]:
    def npm_version(pkg: str) -> str:
        pkg_json = REPO / "node_modules" / pkg / "package.json"
        if not pkg_json.exists():
            return "unknown"
        return str(json.loads(pkg_json.read_text(encoding="utf-8")).get("version", "unknown"))

    return {
        "json-schema-to-typescript": npm_version("json-schema-to-typescript"),
        "typescript": npm_version("typescript"),
    }


def main() -> None:
    check = "--check" in sys.argv
    current = {rel: sha256_of(REPO / rel) for rel in GENERATED_FILES}
    if check:
        if not HASH_FILE.exists():
            print("CHECK FAIL: .gen-hash.json 不存在（请运行 make gen）")
            sys.exit(1)
        recorded = json.loads(HASH_FILE.read_text(encoding="utf-8"))["files"]
        mismatch = [rel for rel, h in current.items() if recorded.get(rel) != h]
        if mismatch:
            print("CHECK FAIL: 生成产物被改动：")
            for rel in mismatch:
                print(f"  - {rel}")
            sys.exit(1)
        print(f"CHECK OK: {len(current)} 个生成产物哈希一致")
    else:
        payload = {
            "_comment": "AUTO-GENERATED by make gen; do not edit",
            "generators": generator_versions(),
            "files": current,
        }
        HASH_FILE.write_text(
            json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        print(f"GEN: packages/schema/.gen-hash.json ({len(current)} files)")


if __name__ == "__main__":
    main()
